class _Delegate extends LocalizationsDelegate<AppStrings> {
  const _Delegate();
  @override
  bool isSupported(Locale locale) => ['en', 'ar'].contains(locale.languageCode);
  @override
  Future<AppStrings> load(Locale locale) => SynchronousFuture(AppStrings(locale));
  @override
  bool shouldReload(_Delegate old) => false;
}

extension L10nX on BuildContext {
  String tr(String key) => AppStrings.of(this).t(key);
  bool get isAr => AppStrings.of(this).isAr;

  /// Picks the Arabic or English variant of a bilingual field.
  String pick(String en, String ar) => isAr && ar.isNotEmpty ? ar : en;

  String money(num value) {
    final currency = Provider.of<AppState>(this, listen: false).currency;
    final symbol = currency == 'EGP' && isAr ? 'ج.م' : currency;
    final amount = value == value.roundToDouble() ? value.toStringAsFixed(0) : value.toStringAsFixed(2);
    return isAr ? '$amount $symbol' : '$symbol $amount';
  }
}
